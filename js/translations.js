// Current language
let currentLanguage = localStorage.getItem('language') || 'nl';

// Apply translations to the page
function applyTranslations(lang) {
    const t = translations[lang];
    if (!t) return;

    // Update HTML lang attribute
    document.documentElement.lang = lang;

    // Get all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (t[key]) {
            // Use innerHTML for keys that contain HTML (like links or spans)
            if (key.includes('title') && key.startsWith('hero') ||
                key.includes('_p1') ||
                key.includes('_info') ||
                key === 'about_p1' ||
                key === 'contact_info') {
                element.innerHTML = t[key];
            } else {
                element.textContent = t[key];
            }
        }
    });

    // Update language selector
    document.getElementById('currentLang').textContent = lang.toUpperCase();

    // Save preference
    localStorage.setItem('language', lang);
    currentLanguage = lang;
}

// Change language
function changeLanguage(lang) {
    applyTranslations(lang);
    // Close dropdown
    document.querySelector('.lang-dropdown').classList.remove('active');
}

// Toggle dropdown
function toggleLangDropdown() {
    document.querySelector('.lang-dropdown').classList.toggle('active');
}

// Close dropdown when clicking outside
document.addEventListener('click', function(e) {
    const dropdown = document.querySelector('.lang-dropdown');
    if (dropdown && !dropdown.contains(e.target)) {
        dropdown.classList.remove('active');
    }
});

// Initialize on page load
document.addEventListener('DOMContentLoaded', function() {
    applyTranslations(currentLanguage);
});
